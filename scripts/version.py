#!/usr/bin/env python3
"""Synchronize all app versions; pre-commit increments from the parent commit."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
FILES = ['VERSION', 'android_app/pubspec.yaml', 'android_app/lib/version.dart', 'ios_app/project.yml', 'ios_app/Weather.xcodeproj/project.pbxproj']

def git(*args, check=True):
    return subprocess.run(['git', *args], cwd=ROOT, text=True, capture_output=True, check=check)

def parent_version(ref='HEAD'):
    result=git('show', f'{ref}:VERSION',check=False)
    return result.stdout.strip() if result.returncode == 0 else None

def next_version(previous):
    if previous is None: return '1.0.0'
    major,minor,patch=map(int,previous.split('.'))
    return f'{major}.{minor}.{patch+1}'

def contents(version):
    build=int(version.split('.')[2])+1
    values={'VERSION':version+'\n','android_app/lib/version.dart':f"// Generated by scripts/version.py.\nconst appVersion = '{version}';\n"}
    for filename in FILES[1:]:
        if filename in values: continue
        text=(ROOT/filename).read_text()
        if filename.endswith('pubspec.yaml'):
            text=re.sub(r'^version: .+$',f'version: {version}+{build}',text,flags=re.M)
        elif filename.endswith('project.yml'):
            text=re.sub(r"MARKETING_VERSION: '[^']+'",f"MARKETING_VERSION: '{version}'",text)
            text=re.sub(r"CURRENT_PROJECT_VERSION: '[^']+'",f"CURRENT_PROJECT_VERSION: '{build}'",text)
        else:
            text=re.sub(r'MARKETING_VERSION = [^;]+;',f'MARKETING_VERSION = {version};',text)
            text=re.sub(r'CURRENT_PROJECT_VERSION = [^;]+;',f'CURRENT_PROJECT_VERSION = {build};',text)
        values[filename]=text
    return values

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--commit',action='store_true')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    current=(ROOT/'VERSION').read_text().strip()
    version=next_version(parent_version()) if args.commit else current
    if args.commit:
        # Never stage someone's unrelated partial edits as a side effect of a hook.
        for file in FILES:
            if (ROOT/file).exists() and git('diff','--',file).stdout:
                raise SystemExit(f'Stage the version-managed file before committing: {file}')
    values=contents(version)
    if args.check:
        for filename,expected in values.items():
            if not (ROOT/filename).exists() or (ROOT/filename).read_text() != expected:
                raise SystemExit(f'Version mismatch: {filename}')
        previous=parent_version('HEAD^')
        if current != next_version(previous):
            raise SystemExit(f'Expected {next_version(previous)}, found {current}')
        print(f'Versions verified: {current}')
        return
    for filename,text in values.items(): (ROOT/filename).write_text(text)
    if args.commit: git('add','--',*FILES)
    print(f'Version: {version}')

if __name__ == '__main__': main()
